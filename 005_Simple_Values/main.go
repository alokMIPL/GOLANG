package main

import "fmt"

func main() {

	// Simple Values

	// int
	fmt.Println(1)
	fmt.Println(1 + 1)

	// string
	fmt.Println("Hello Go")

	// boolean
	fmt.Println(true)
	fmt.Println(false)

	// floats
	fmt.Println(10.4)

	// Arithmatic Operations
	fmt.Println(7.0 / 3.5)

}

/*
Output
1
2
Hello Go
true
false
10.4
2

*/
